import 'dart:ffi';

import 'package:hollat/main/data/models/ticket/old_ticket/file_model.dart';
import 'package:hollat/main/data/models/ticket/old_ticket/main_reason_model.dart';
import 'package:hollat/main/domain/entities/ticket/old_ticket/data_ticket.dart';

class DataTicketModel extends DataTicket {
  const DataTicketModel({required super.addedByClient,
    required super.address,
    required super.alreadyEscalated,
    required super.createdAt,
    required super.details,
    required super.files,
    required super.id,
    required super.lastAssignedUserAt,
    required super.lastStatusUpdatedAt,
    required super.latitude,
    required super.locationUrl,
    required super.longitude,
    required super.mainReason,
    required super.mainReasonId,
    required super.mustRespondedBefore,
    required super.priorityId,
    required super.requesterId,
    required super.resolvedAt,
    required super.responsibleOrganizationId,
    required super.sectorReply,
    required super.sequenceNumber,
    required super.slaId,
    required super.slaStatusId,
    required super.solution,
    required super.solvedBy,
    required super.sourceId,
    required super.statusId,
    required super.subReason,
    required super.subReasonId,
    required super.subReasonOther,
    required super.subSubReasonId,
    required super.subSubSubReasonId,
    required super.ticketCreatedAt,
    required super.ticketNumber,
    required super.ticketReferenceNumber,
    required super.ticketTypeId,
    required super.updatedAt,
    required super.userId,
    required super.workflowStatusId});

  factory DataTicketModel.fromJson(Map<String, dynamic>json)=>
      DataTicketModel(addedByClient: json['added_by_client'] as int,
          address: json['address'] as String?,
          alreadyEscalated: json['already_escalated'] as int,
          createdAt: json['created_at'] as String,
          details: json['details'] as String?,
          files: (json['files'] as List<dynamic>).map( (fileJson) => FileModel.fromJson(fileJson)).toList(),
          id: json['id'] as Long?,
          lastAssignedUserAt: json['last_assigned_user_at'] as String?,
          lastStatusUpdatedAt: json['last_status_updated_at'] as String?,
          latitude: json['latitude'] as String?,
          locationUrl: json['location_url'] as String?,
          longitude: json['longitude'] as String?,
          mainReason: MainReasonModel.fromJson(json['main_reason'] as Map<String,dynamic>),
          mainReasonId: json[''] as int,
          mustRespondedBefore: json['must_resolved_before'] as String?,
          priorityId: json['priority_id'] as int,
          requesterId: json['requester_id'] as int,
          resolvedAt: json['resolved_at'] as String?,
          responsibleOrganizationId: json['responsible_organization_id'] as int,
          sectorReply: json['sector_reply'] as String?,
          sequenceNumber: json['sequence_number'] as String,
          slaId: json['sla_id'] as int?,
          slaStatusId: json['sla_status_id'] as int,
          solution: json['solution'] as String?,
          solvedBy: json['solved_by'] as int,
          sourceId: json['source_id'] as int,
          statusId: json['status_id'] as int,
          subReason: MainReasonModel.fromJson(json['main_reason'] as Map<String,dynamic>),
          subReasonId: json['sub_reason_id'] as int,
          subReasonOther: json['sub_reason_other'] as String?,
          subSubReasonId: json['sub_sub_reason_id'] as int,
          subSubSubReasonId: json['sub_sub_sub_reason_id'] as String?,
          ticketCreatedAt: json['ticket_created_at'] as String?,
          ticketNumber: json['ticket_number'] as int,
          ticketReferenceNumber: json['ticket_reference_number'] as String?,
          ticketTypeId: json['ticket_type_id'] as int,
          updatedAt: json['updated_at'] as String,
          userId: json['user_id'] as int,
          workflowStatusId: json['workflow_status_id'] as int?
      );
}
